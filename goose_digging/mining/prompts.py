# ===========================================================================
# user prompt 构造函数
# ===========================================================================
def fluency_prompt(strs: list[str]) -> str:
    """T1: 批量判断每个短语"讲得通不通" (三选一即通顺), 给便宜模型.

    strs: 待判短语列表 (一个 pair 的 left/right 拆开混在一起).
    判据宽松: 在词典里/真实词, 或解释得通的词语 (谐音/口语), 或能作为句子的一部分, 任一即通顺.
    返回 prompt. 模型回 {"items":[{"text","ok"}]}.
    """
    n = len(strs)
    lines = "\n".join(f"{i}. {s}" for i, s in enumerate(strs))
    return f"""判断下面每个, 单独看, 是不是"讲得通" (满足任一即 true, 别太严):
- 是真实词/成语/常用搭配
- 是个解释得通的词语 (谐音撞意思、口语俚语、略不规范但讲得通都算)
- 可以作为句子的一部分 (能塞进一句话里说得通)
只有"字硬拼/纯随机字组合/明显乱码"才判 false.

待判 ({n} 个, 必须全部回, 一个都不能少):
{lines}

只输出 JSON: {{"items": [{{"text": "<原词>", "ok": true或false}}]}}
要求: items 数组必须正好 {n} 条, 与上面逐个一一对应, 不许漏.
只输出 JSON 对象."""


def score_prompt(pairs: list[dict]) -> str:
    """T2: 关系评分. 前提是两边都已通过 T1 通顺预筛, 这里只判关系神不神.

    pairs 每条 {left, right}. 返回 0-10 分 + why.
    """
    n = len(pairs)
    lines = [f"{i}. {p['left']} → {p['right']}" for i, p in enumerate(pairs)]
    block = "\n".join(lines)
    return f"""
下面每条 pair (左, 右=goose(左)), 两边都已确认通顺. 按系统提示打分.

待评 ({n} 条, 必须全部回, 一条都不能少):
{block}

只输出 JSON: {{"scores": [{{"left": "<原左>", "score": <0-10>, "why": "<解释打分原因，简短一句话别太长>"}}]}}
要求: scores 数组必须正好 {n} 条, 与上面逐条一一对应, 不许合并/省略/漏.
why 尽量短 (一句话), 别展开故事. 只输出 JSON 对象."""
